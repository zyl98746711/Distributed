/**
 * <h2>distributed-ratelimit - 分布式限流</h2>
 *
 * <h3>为什么需要限流?</h3>
 * <ul>
 *   <li>保护服务: 防止突发流量压垮系统</li>
 *   <li>保证 SLA: 在容量范围内提供服务</li>
 *   <li>公平分配: 防止单一用户占用所有资源</li>
 * </ul>
 *
 * <h3>四种算法对比</h3>
 * <pre>
 * 固定窗口:  简单但有边界问题 (0.9s 和 1.1s 可能通过 2x 请求)
 * 滑动窗口:  精确但内存占用大 (需要记录每个请求时间戳)
 * 令牌桶:    允许突发，限制平均速率 (API 网关常用)
 * 漏桶:      严格恒定速率 (适合数据库写入等场景)
 * </pre>
 *
 * <h3>选择建议</h3>
 * <ul>
 *   <li>一般 API 限流 → 令牌桶 (允许一定突发)</li>
 *   <li>严格恒定速率 → 漏桶</li>
 *   <li>简单场景 → 固定窗口</li>
 *   <li>精确控制 → 滑动窗口</li>
 * </ul>
 */
