/**
 * <h2>distributed-id - 分布式 ID 生成器</h2>
 *
 * <h3>为什么分布式 ID 比单机 ID 难？</h3>
 * <p>单机用自增 long 就够了。分布式环境下需要:</p>
 * <ul>
 *   <li><b>全局唯一</b>: 不同节点不能生成相同 ID</li>
 *   <li><b>趋势递增</b>: 有利于数据库 B+Tree 索引</li>
 *   <li><b>高性能</b>: 不依赖外部服务 (如 DB)</li>
 *   <li><b>高可用</b>: 某个节点挂了不影响其他节点</li>
 * </ul>
 *
 * <h3>两种方案</h3>
 * <pre>
 * 雪花算法 (Snowflake):
 *   0 | 41位时间戳 | 10位机器ID | 12位序列号
 *   优点: 本地生成，无依赖，高性能
 *   挑战: 时钟回拨
 *
 * 号段模式 (Segment):
 *   批量获取号段 → 本地分配 → 用完再取
 *   优点: 减少外部存储访问
 *   挑战: 需要外部存储 (DB/文件)
 * </pre>
 */
